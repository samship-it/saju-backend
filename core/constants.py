# 궁합/결혼 점수 -> 관계 타입 + 한줄평 (기획 문서 표 그대로)
COMPAT_BANDS = [
    (90, 100, "💍 천생연분", "이 정도면 결혼각 💍"),
    (80, 89, "🏠 반려생활", "우린 장기전에 강해요."),
    (70, 79, "🧩 찰떡짝꿍", "생각보다 우리, 잘 맞는데?"),
    (60, 69, "💕 짝꿍연습중", "이심전심, 조금만 더 해보자!"),
    (50, 59, "💌 더 가까이", "좀 더 다가와줄래?"),
    (40, 49, "🌱 노력형 사랑", "사랑은 주는 거니까."),
    (30, 39, "↔️ 다른 사람", "우리, 좀 다르네."),
    (0, 29, "─ 평행선", "좋아하는 마음만으로는 조금 어려워요."),
]


def score_to_emoji(score: int) -> str:
    s = max(0, min(100, int(round(score))))
    for lo, hi, emoji in SCORE_EMOJI_BANDS:
        if lo <= s <= hi:
            return emoji
    return "🙂"


def score_to_band(score: int) -> str:
    s = max(0, min(100, int(round(score))))
    for lo, hi, _ in SCORE_EMOJI_BANDS:
        if lo <= s <= hi:
            return f"{lo}-{hi}"
    return "50-59"


def compat_band(score: int):
    s = max(0, min(100, int(round(score))))
    for lo, hi, rel_type, one_liner in COMPAT_BANDS:
        if lo <= s <= hi:
            return {"relation_type": rel_type, "one_liner": one_liner, "band": f"{lo}-{hi}"}
    return {"relation_type": "─ 평행선", "one_liner": "좋아하는 마음만으로는 조금 어려워요.", "band": "0-29"}

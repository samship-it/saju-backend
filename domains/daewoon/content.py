def build_child_domains(sipsin: str) -> Dict[str, Dict[str, str]]:
    """20세 미만 전용 domain_analysis — [학업/성장]/[용돈/경제관념]/[교우/친구관계]/[부모/가정환경].

    study_growth는 10종 각각 완전히 다른 표(STUDY_GROWTH)를 쓰고, 나머지 3영역은
    5분류 기반 문단에 10종별 한 문장을 덧붙여(*_NUANCE) 정/편이 절대 같은 문구를
    내지 않도록 한다.
    """
    group = sipsin_group(sipsin)

    study = {field: _assert_child_safe(text) for field, text in _fallback(STUDY_GROWTH, sipsin).items()}

    allowance = dict(_fallback(ALLOWANCE_ECONOMY, group))
    allowance_nuance = ALLOWANCE_NUANCE.get(sipsin)
    if allowance_nuance:
        allowance["allowance_flow"] = _assert_child_safe(f"{allowance['allowance_flow']} {allowance_nuance}")
    else:
        allowance = {k: _assert_child_safe(v) for k, v in allowance.items()}

    friendship = dict(_fallback(FRIENDSHIP, group))
    friendship_nuance = FRIENDSHIP_NUANCE.get(sipsin)
    if friendship_nuance:
        friendship["peer_relationship"] = _assert_child_safe(f"{friendship['peer_relationship']} {friendship_nuance}")
    else:
        friendship = {k: _assert_child_safe(v) for k, v in friendship.items()}

    family_env = dict(_fallback(FAMILY_ENVIRONMENT, group))
    family_env_nuance = FAMILY_ENV_NUANCE.get(sipsin)
    if family_env_nuance:
        family_env["parent_relationship"] = _assert_child_safe(
            f"{family_env['parent_relationship']} {family_env_nuance}"
        )
    else:
        family_env = {k: _assert_child_safe(v) for k, v in family_env.items()}

    return {
        "study_growth": study,
        "allowance_economy": allowance,
        "friendship": friendship,
        "family_environment": family_env,
    }


def build_career_or_study(sipsin: str, is_adult: bool) -> Dict[str, str]:
    table = CAREER_ADULT if is_adult else CAREER_YOUTH
    return dict(_fallback(table, sipsin))


def build_wealth_flow(sipsin: str) -> Dict[str, str]:
    group = sipsin_group(sipsin)
    wealth = dict(_fallback(WEALTH_FLOW, group))
    nuance = WEALTH_NUANCE.get(sipsin)
    if nuance:
        wealth["earning_style"] = f"{wealth['earning_style']} {nuance}"
    return wealth


def build_relationship(sipsin: str, love_status: Optional[str], is_current: bool) -> Dict[str, object]:
    group = sipsin_group(sipsin)
    guide = None
    if is_current and love_status in RELATIONSHIP_STATUS_GUIDE:
        guide = {love_status: RELATIONSHIP_STATUS_GUIDE[love_status]}
    elif is_current:
        guide = dict(RELATIONSHIP_STATUS_GUIDE)
    flow = RELATIONSHIP_FLOW.get(group, RELATIONSHIP_FLOW["비겁"])
    nuance = RELATIONSHIP_NUANCE.get(sipsin)
    if nuance:
        flow = f"{flow} {nuance}"
    return {
        "flow": flow,
        "guide_by_status": guide,
    }


def build_family(sipsin: str) -> Dict[str, str]:
    group = sipsin_group(sipsin)
    family = dict(_fallback(FAMILY_FLOW, group))
    nuance = FAMILY_NUANCE.get(sipsin)
    if nuance:
        family["change_flow"] = f"{family['change_flow']} {nuance}"
    return family



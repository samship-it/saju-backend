# 완전히 대체한다. "직장"·"자산 관리"·"배우자"·"연애"처럼 성인 전용 단어는 이
# 표들에 절대 쓰지 않고, _assert_child_safe()로 빌드 시점마다 강제 검증한다
# (표를 잘못 고쳐도 즉시 예외로 걸러진다).
FORBIDDEN_ADULT_WORDS: List[str] = ["직장", "자산 관리", "배우자", "연애"]


def _assert_child_safe(text: str) -> str:
    for word in FORBIDDEN_ADULT_WORDS:
        if word in text:
            raise ValueError(f"20세 미만 대운 문구에 성인 전용 단어 '{word}'가 포함되어 있습니다: {text!r}")
    return text



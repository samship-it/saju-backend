def _rename(text: str, src: str, dst: str) -> str:
    """호칭을 바꿀 때 조사까지 같이 맞춘다. 긴 형태를 먼저 바꾼다."""
    dj = _josa(dst)
    pairs = [
        (src + "입니다", dst + "입니다"),
        (src + "이에요", dst + "이에요"),
        (src + "예요", dst + "예요"),
        (src + "임을", dst + "임을"),
        (src + "이라는", dst + "이라는"),
        (src + "이자", dst + "이자"),
        (src + "라는", dst + "라는"),
        (src + "이란", dst + "이란"),
        (src + "으로", dst + dj["로"]),
        (src + "로", dst + dj["로"]),
        (src + "과", dst + dj["와"]),
        (src + "와", dst + dj["와"]),
        (src + "을", dst + dj["를"]),
        (src + "를", dst + dj["를"]),
        (src + "은", dst + dj["는"]),
        (src + "는", dst + dj["는"]),
        (src + "이", dst + dj["가"]),
        (src + "가", dst + dj["가"]),
        (src + "에", dst + "에"),
        (src + "의", dst + "의"),
        (src, dst),
    ]
    pairs.sort(key=lambda pair: len(pair[0]), reverse=True)
    return _apply(text, tuple(pairs))



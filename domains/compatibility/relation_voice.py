def _josa(word: str) -> dict:
    batchim = _batchim(word)
    if batchim == 0:
        return {"가": "가", "를": "를", "와": "와", "는": "는", "로": "로", "에": "에"}
    if batchim == 8:
        return {"가": "이", "를": "을", "와": "과", "는": "은", "로": "로", "에": "에"}
    return {"가": "이", "를": "을", "와": "과", "는": "은", "로": "으로", "에": "에"}


def _swap_open_noun(src: str, dst: str) -> tuple:
    """받침 없는 말 뒤의 조사를, 바뀐 말에 맞게 다시 붙인다."""
    josa = _josa(dst)
    return (
        (src + "가", dst + josa["가"]),
        (src + "를", dst + josa["를"]),
        (src + "와", dst + josa["와"]),
        (src + "로", dst + josa["로"]),
        (src + "는", dst + josa["는"]),
        (src + "에", dst + josa["에"]),
        (src, dst),
    )


def _rewrite_kurida(text: str, obj: str) -> str:
    ordered = sorted(_KURI_TAIL, key=lambda pair: len(pair[0]), reverse=True)
    alt = "|".join(re.escape(src) for src, _ in ordered)
    mapped = dict(ordered)

    def repl(match: re.Match) -> str:
        adverb = match.group(1) or ""
        return f"{obj}{adverb} {mapped[match.group(2)]}"

    return re.sub(
        rf"살림을((?:\s+[가-힣]{{2,10}}(?:하게|적으로|히))?)\s*({alt})",
        repl,
        text,
    )


def _shift_watch(text: str, obj: str) -> str:
    """원문의 챙기다·살피다는 남기고, 살림만 그 관계의 대상으로 바꾼다."""

    def repl(match: re.Match) -> str:
        adverb = match.group(1) or ""
        return f"{obj}{adverb} {match.group(2)}"

    return re.sub(
        r"살림을((?:\s+[가-힣]{2,10}(?:하게|적으로|히))?)\s*((?:챙기|살피)[가-힣]*)",
        repl,
        text,
    )


def _adapt_economy(text: str, key: str) -> str:
    """경제 문장만 다듬는다. 가족은 살림이 그 관계의 말이므로 그대로 둔다."""
    if key not in _THRIFT_OBJECT:
        return text
    text = _apply(text, _ECONOMY_SPECIAL[key])
    text = _apply(text, _swap_open_noun("살림 솜씨", _SENSE[key]))
    text = _apply(text, _swap_open_noun("살림 팁", "요령"))
    person = _PERSON[key]
    text = _apply(
        text,
        (
            ("살림꾼답게", person + "답게"),
            ("살림꾼처럼", person + "처럼"),
            ("살림꾼입니다", person + "입니다"),
            ("살림꾼이에요", person + "이에요"),
            ("살림꾼의", person + "의"),
            ("살림꾼과", person + "와"),
            ("살림꾼인", person + "인"),
            ("살림꾼", person),
        ),
    )
    text = _rewrite_kurida(text, _THRIFT_OBJECT[key])
    text = _shift_watch(text, _WATCH_OBJECT[key])
    text = text.replace("살림력", _SENSE[key])
    wa, ga, neun, e, ui, bare = _LEFTOVER[key]
    text = _apply(
        text,
        (
            ("살림과", wa),
            ("살림이", ga),
            ("살림은", neun),
            ("살림에", e),
            ("살림의", ui),
            ("살림을", _THRIFT_OBJECT[key]),
            ("살림", bare),
        ),
    )
    return text



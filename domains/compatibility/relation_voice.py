def _hug_suffix(ending: str) -> str:
    for src, dst in _HUG_SUFFIX:
        if ending == src:
            return dst
    return "한다"


def _replace_hug(text: str, key: str) -> str:
    def repl(match: re.Match) -> str:
        ending = match.group(0)
        stem = ending
        for adverb in ("포근하게 ", "따뜻하게 ", "부드럽게 ", "다정하게 ", "꼬옥 "):
            if stem.startswith(adverb):
                stem = stem[len(adverb):]
                break
        if stem.startswith("감싸"):
            stem = re.sub(r"^감싸\s*", "", stem)
        if stem.startswith("안아"):
            stem = stem[2:]
        elif stem.startswith("안"):
            stem = stem[1:]
        suffix = _hug_suffix(stem)
        prev = text[: match.start()].rstrip()
        prev = re.sub(
            r"(?:꼭|살며시|꼬옥|포근하게|따뜻하게|부드럽게|다정하게|먼저|가만히)$",
            "",
            prev,
        ).rstrip()
        emotion = bool(re.search(r"(?:감성|마음|감정|상처)[을를]$", prev))
        if emotion:
            base = "이해" if key == "family" else "존중"
        elif prev.endswith(("을", "를")):
            base = _HUG_BARE[key]
        else:
            base = _HUG_FULL[key]
        return base + suffix

    return _HUG_RE.sub(repl, text)


def _replace_fall(text: str, key: str) -> str:
    def repl(match: re.Match) -> str:
        before = text[: match.start()]
        if re.search(r"[을를]\s*$", before):
            return match.group(0)
        return _FALL[key]

    return _FALL_RE.sub(repl, text)


def _reframe(text: str, key: str) -> str:
    """연인 장면만 그 관계의 행동으로 바꾼다. 성향을 가리키는 수식은 남긴다."""
    if key not in _HANDS:
        return text
    text = text.replace("넓은 마음으로 받아주면", _YIELD[key])
    text = _apply(text, _HANDS[key])
    text = _apply(text, _TOGETHER[key])
    text = _replace_hug(text, key)
    text = _replace_fall(text, key)
    text = _apply(text, _ARM[key])
    text = _apply(text, _WALK[key])
    text = text.replace("둘만의", _PAIR[key])
    text = _apply(text, _GAZE[key])
    text = _rename(text, "안식처", _HAVEN[key])
    text = _rename(text, "짝꿍", _MATE[key])
    text = _rename(text, "동반자", _MATE[key])
    text = text.replace("달콤한", _SWEET[key])
    text = text.replace("알콩달콩", _CUTE[key])
    text = _rename(text, "설렘", _FLUTTER[key])
    text = text.replace("설레는", _FLUTTER[key] + " ")
    if key == "family":
        text = _apply(
            text,
            (
                ("포옹 한 번", "대화 한 번"),
                ("포옹이나", "다독임이나"),
                ("포옹으로", "대화로"),
                ("포옹", "다독임"),
            ),
        )
    if key in _WARMTH:
        text = _rename(text, "온기", _WARMTH[key])
    text = text.replace("다정한 쉼표", "편한 호흡" if key in ("friend", "family") else "숨 고르기")
    return text


def adapt_text(text: str, relation_type: str, field: str = "") -> str:
    """한 필드의 일주 해설을 관계에 맞게 다듬는다. 연인은 원문 그대로다."""
    if not text:
        return text
    key = (relation_type or "romantic").strip().lower()
    if key in ("", "romantic"):
        return text
    if key == "spouse":
        return _apply(text, _SPOUSE)
    if key == "general":
        key = "acquaintance"
    if key not in _BY_RELATION:
        key = "acquaintance"
    out = _apply(text, _SHARED)
    out = _apply(out, _BEFORE.get(key, ()))
    out = _apply(out, _BY_RELATION[key])
    if key in _THRIFT_OBJECT:
        out = _adapt_economy(out, key)
    out = _reframe(out, key)
    return _fix_particles(_guard_people(out))



_BROKEN_LEAD = re.compile(r"^(?:[을를이가은는에와과]\s|때는|위해서는|지점은)")
_RESOLUTION_OPEN = re.compile(
    r"^갈등을\s+"
    r"(?:[가-힣]{1,8}(?:고|게|히)\s+){0,4}"
    r"(?:풀고 싶다면|풀어나가려면|풀어가려면|풀어내려면|풀려면|풀기 위해서는|"
    r"풀어나가기 위해서는|풀어내기 위해서는|극복하려면|극복하기 위해서는|"
    r"해결하려면|해결하는 비결은|해결하는 과정은|해결하는 가장 좋은 방법은|"
    r"매듭짓는 가장 좋은 방법은|매듭지을 때는|풀어내는 법은)\s*"
)


def trim_section_lead(field: str, text: str) -> str:
    """제목과 같은 도입부만 뺀다. 빼면 조사가 어색해지면 원문을 둔다."""
    leads = _SECTION_LEADS.get(field)
    if not text or not leads:
        return text
    ordered = sorted(leads, key=len, reverse=True)
    for lead in ordered:
        match = re.match(re.escape(lead) + r"\s*", text)
        if not match:
            continue
        rest = text[match.end():].lstrip()
        if rest and not _BROKEN_LEAD.match(rest):
            return rest
    if field == "conflict_resolution":
        match = _RESOLUTION_OPEN.match(text)
        if match:
            rest = text[match.end():].lstrip()
            if rest and not _BROKEN_LEAD.match(rest):
                return rest
    return text


def adapt_report(raw: Dict[str, str], relation_type: str) -> Dict[str, str]:
    """7개 필드를 같은 기준으로 다듬는다. 없는 칸은 빈 문자열이다."""
    key = (relation_type or "romantic").strip().lower()
    fields = (
        "overall",
        "love",
        "communication",
        "conflict",
        "conflict_resolution",
        "economy",
        "relationship_advice",
    )
    adapted = {name: adapt_text(str(raw.get(name, "")), key, field=name) for name in fields}
    if key not in ("", "romantic", "spouse"):
        # 애정 카드는 연인·배우자 화면에만 둔다. 점수는 그대로다.
        adapted["love"] = ""
    return {name: trim_section_lead(name, text) for name, text in adapted.items()}

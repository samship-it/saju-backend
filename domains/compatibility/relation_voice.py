def _batchim(word: str) -> int:
    code = ord(word[-1])
    if 0xAC00 <= code <= 0xD7A3:
        return (code - 0xAC00) % 28
    return 0


def _fix_particles(text: str) -> str:
    edge = r"(?=[\s,.!?」]|$)"
    for noun in _OPEN_NOUNS:
        text = re.sub(noun + r"으로(?!서)", noun + "로", text)
        text = re.sub(noun + "을" + edge, noun + "를", text)
        text = re.sub(noun + "은" + edge, noun + "는", text)
        text = re.sub(noun + "과" + edge, noun + "와", text)
        text = re.sub(noun + "이" + edge, noun + "가", text)
    for noun in _CLOSED_NOUNS:
        text = re.sub(noun + "를" + edge, noun + "을", text)
        text = re.sub(noun + "는" + edge, noun + "은", text)
        text = re.sub(noun + "가" + edge, noun + "이", text)
        text = re.sub(noun + "와" + edge, noun + "과", text)
        # ㄹ 받침은 '일로'가 맞다. '일으로'로 바꾸지 않는다.
        if _batchim(noun) not in (0, 8):
            text = re.sub(rf"(?<!으){noun}로" + edge, noun + "으로", text)
    return text


def _apply(text: str, pairs: tuple) -> str:
    out = text
    for old, new in pairs:
        if old in out:
            out = out.replace(old, new)
    return out


def _guard_people(text: str) -> str:
    """참아내·들여보세요 같은 말 속의 글자는 건드리지 않는다."""
    text = _WIFE.sub("상대", text)
    text = _HONEY.sub("상대", text)
    return text.replace("남편", "상대")


def adapt_text(text: str, relation_type: str, field: str = "") -> str:
    """한 필드의 일주 해설을 관계에 맞게 다듬는다. 연인은 원문 그대로다."""
    if not text:
        return text
    key = (relation_type or "romantic").strip().lower()
    if key in ("", "romantic"):
        return text
    if key == "spouse":
        return _apply(text, _SPOUSE)
    if key == "general":
        key = "acquaintance"
    if key not in _BY_RELATION:
        key = "acquaintance"
    out = _apply(text, _SHARED)
    out = _apply(out, _BEFORE.get(key, ()))
    out = _apply(out, _BY_RELATION[key])
    if field == "economy":
        out = _adapt_economy(out, key)
    return _fix_particles(_guard_people(out))



def deepen_character(raw: dict) -> dict:
    """저장된 문단은 유지하고, 그 문단에 근거가 있는 행동 설명만 뒤에 붙인다.

    조회 캐시의 dict 를 그대로 고치지 않는다. 고치면 다음 조회가 문단을 중복으로 붙인다.
    """
    source = raw or {}
    out = {key: source.get(key, "") for key in _FIELDS}
    for key in _FIELDS:
        text = str(out.get(key) or "")
        extras = []
        for name in matched(text):
            paragraph = _EXTRA.get(key, {}).get(name)
            if not paragraph or shares(text, paragraph):
                continue
            extras.append(paragraph)
        if not extras:
            continue
        body = paragraphize(text)
        out[key] = body.rstrip() + "\n\n" + "\n\n".join(extras)
    return out

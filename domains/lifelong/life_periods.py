def build_late_life(saju: Dict[str, Any], facts: List[Dict[str, Any]], daewoon_num: int) -> Dict[str, Any]:
    day_master = saju.get("day_master", "")
    time_ganji = saju.get("time_ganji") or ""
    if saju.get("birth_time_known", True) and len(time_ganji) >= 2:
        anchor_sipsin = calculate_sipsin(day_master, time_ganji[0], is_gan=True)
    else:
        # 출생시간 미상이면 시주 대신 일지(日支) — 이미 계산돼 있는 값 재사용.
        day_branch = saju.get("day_branch", "")
        anchor_sipsin = calculate_sipsin(day_master, day_branch, is_gan=False) if day_branch else ""
    group = sipsin_group(anchor_sipsin) if anchor_sipsin else "비겁"
    if group not in GROUPS:
        group = "비겁"

    g70 = _group_at_age(facts, daewoon_num, 75)
    g80 = _group_at_age(facts, daewoon_num, 85)
    decade_transition = f"70대에는 {_PHASE_70S[g70]}. 80대에 접어들면 {_PHASE_80S[g80]}."

    return {
        "daily_lifestyle": _DAILY_LIFESTYLE[group],
        "financial_status": _FINANCIAL_STATUS[group],
        "family_bonds": _FAMILY_BONDS_LATE[group],
        "mental_social_role": _MENTAL_SOCIAL_ROLE[group],
        "decade_transition": decade_transition,
        "summary_one_line": _LATE_SUMMARY[group],
    }

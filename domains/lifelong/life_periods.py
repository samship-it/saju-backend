from typing import Any, Dict, List, Optional

from core.sipsin import calculate_sipsin, sipsin_group

GROUPS: List[str] = ["비겁", "식상", "재성", "관성", "인성"]


def _step_covering_age(facts: List[Dict[str, Any]], daewoon_num: int, target_age: int) -> int:
    """8단계 대운 중 target_age 를 실제로 포함하는 단계. 정확히 포함하는 단계가 없으면
    (예: 대운수가 커서 특정 나이대가 8단계 범위 밖인 경우) 가장 가까운 단계로 폴백."""
    best_step, best_dist = 1, None
    for f in facts:
        step = f["step"]
        start = daewoon_num + (step - 1) * 10
        end = start + 9
        if start <= target_age <= end:
            return step
        dist = min(abs(target_age - start), abs(target_age - end))
        if best_dist is None or dist < best_dist:
            best_dist, best_step = dist, step
    return best_step


def _group_at_age(facts: List[Dict[str, Any]], daewoon_num: int, target_age: int) -> str:
    step = _step_covering_age(facts, daewoon_num, target_age)
    fact = next((f for f in facts if f["step"] == step), None)
    return fact["sipsin_group"] if fact else "비겁"



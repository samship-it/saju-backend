def couple_piece(role: str, kind: str, field: str) -> str:
    row = _ROLE[role]
    if field == "balance":
        return row["balance"]
    if field in ("why", "advantage", "obstacle", "charm", "m1", "m2", "m3"):
        return row[field]
    headline, overall, conflict = _KIND[role][kind]
    return {"headline": headline, "overall": overall, "conflict": conflict}[field]


def strategy_intro(track: str) -> str:
    return _INTRO.get(track, _INTRO["open"])

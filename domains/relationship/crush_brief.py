def _kind(flags: Dict[str, bool]) -> str:
    if flags.get("missing"):
        return "open"
    if flags["hap"] and (flags["chung"] or flags["hae"] or flags["hyung"] or flags["pa"]):
        return "mixed"
    if flags["chung"]:
        return "chung"
    if flags["hyung"]:
        return "hyung"
    if flags["hae"]:
        return "hae"
    if flags["self_hyung"]:
        return "self"
    if flags["same"]:
        return "same"
    if flags["pa"]:
        return "pa"
    if flags["hap"]:
        return "hap"
    return "open"


def _flags(branch_a: str, branch_b: str) -> Dict[str, bool]:
    if not branch_a or not branch_b:
        return {
            "missing": True, "hap": False, "chung": False, "pa": False,
            "hae": False, "hyung": False, "same": False, "self_hyung": False,
        }
    key = frozenset((branch_a, branch_b))
    hyung = key in SANGHYEONG
    if branch_a != branch_b:
        for group, _name in SAMHYEONG:
            if branch_a in group and branch_b in group:
                hyung = True
    same = branch_a == branch_b
    return {
        "missing": False,
        "hap": key in YUKHAP,
        "chung": key in CHUNG,
        "pa": key in PA,
        "hae": key in HAE,
        "hyung": hyung,
        "same": same,
        "self_hyung": same and branch_a in SELF_HYEONG,
    }


def _role_name(self_ganji: str, partner_ganji: str) -> str:
    mine = GAN_ELEM.get((self_ganji or "")[:1])
    theirs = GAN_ELEM.get((partner_ganji or "")[:1])
    if not mine or not theirs:
        return "비겁"
    return FIVE_ELEMENT_RELATIONS[(mine, theirs)]


def _stem(ganji: str) -> Dict[str, str]:
    gan = (ganji or "")[:1]
    return _SOLO.get(gan, _SOLO["戊"])


def _join(*parts: str) -> str:
    return " ".join(part.strip() for part in parts if part and part.strip())


def build_crush_brief(self_ganji: str, partner_ganji: Optional[str]) -> Dict[str, object]:
    """짝사랑 화면에 올릴 한줄평과 신규 구획. 저장된 원문은 넣지 않는다."""
    me = _stem(self_ganji or "")

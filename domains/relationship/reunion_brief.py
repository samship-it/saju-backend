def _kind(flags: Dict[str, bool]) -> str:
    if flags.get("missing"):
        return "missing"
    if flags["hap"] and _friction(flags):
        return "mixed"
    if flags["chung"]:
        return "chung"
    if flags["hyung"]:
        return "hyung"
    if flags["hae"]:
        return "hae"
    if flags["self_hyung"]:
        return "self"
    if flags["same"]:
        return "same"
    if flags["pa"]:
        return "pa"
    if flags["hap"]:
        return "hap"
    return "open"



def _relation_bucket(relation: str) -> str:
    """core.daewoon.branch_relation() 의 반환 문자열 -> 6가지 관계 버킷."""
    r = relation or ""
    if r.startswith("육합"):
        return "harmony"
    if r.startswith("충"):
        return "conflict"
    if r.startswith("형"):
        return "adjustment"
    if r.startswith("파") or r.startswith("해"):
        return "friction"
    if r.startswith("복음"):
        return "repeat"
    return "neutral"



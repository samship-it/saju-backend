def rewrite_health_sentence(sentence: str) -> str:
    if "맥주 한 잔" in sentence or "건강한 안주" in sentence:
        for old, new in _SWAPS[-2:]:
            sentence = sentence.replace(old, new)
        return sentence
    if not _MEAL.search(sentence) or not _META.search(sentence):
        return sentence
    if any(skip in sentence for skip in _SKIP):
        return sentence
    for old, new in _SWAPS[:-2]:
        sentence = sentence.replace(old, new)
    return sentence


def rewrite_health_text(text: str) -> str:
    if not isinstance(text, str) or ("대사" not in text and "맥주" not in text and "안주" not in text):
        return text
    parts = re.split(r"((?<=[\.!?])\s+)", text)
    return "".join(
        piece if index % 2 else rewrite_health_sentence(piece)
        for index, piece in enumerate(parts)
    )
